"""Generate readable Linux/CUDA code from the same run02 training cells."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXPERIMENTS = HERE.parent / 'colab_t4' / 'experiments'


def build():
    notebook = json.loads((EXPERIMENTS / 'train_stage2.ipynb').read_text())
    parts = ['# Generated by remote/build_worker.py; do not edit this file directly.']
    for cell in notebook['cells']:
        if cell['cell_type'] != 'code':
            continue
        source = ''.join(cell['source'])
        label = source.splitlines()[0]
        if label == '# [config]':
            source = '''# [config]
import argparse, json, os, sys
from pathlib import Path
parser = argparse.ArgumentParser()
parser.add_argument('phase', choices=['merge', 'train'])
parser.add_argument('--workspace', type=Path, required=True)
parser.add_argument('--run-id', required=True)
args = parser.parse_args()
PHASE = args.phase
RUN_ID = args.run_id
WORKSPACE = str(args.workspace.expanduser().resolve())
STAGE1_DIR = WORKSPACE + '/adapters/t4_20261013_run01_stage1'
STAGE2_DIR = WORKSPACE + '/adapters/' + RUN_ID + '_stage2'
MERGED_STAGE1 = WORKSPACE + '/merged/run01_stage1'
RUN_DIR = WORKSPACE + '/experiments/' + RUN_ID
COUNTS = {'prm800k': 1500, 'gsm8k': 500}
MAX_LENGTH = 2048
EPOCHS = 1.0
LEARNING_RATE = 5e-5
LORA_R, LORA_ALPHA = 8, 16
GRAD_ACCUM = 16
SEED = 42
EXPERIMENTS = Path(__file__).resolve().parents[1] / 'colab_t4' / 'experiments'
sys.path.insert(0, str(EXPERIMENTS))
'''
        elif label == '# [guard-and-install]':
            source = '''# [guard-and-install]
import subprocess, hashlib, time, gc, platform
if platform.system() != 'Linux':
    raise RuntimeError('Linux/CUDA用です。Macでは学習を開始しません。')
'''
        elif label == '# [reference]':
            source = '''# [reference]
REFERENCE = json.loads((EXPERIMENTS / 'run02_reference.json').read_text())
CHAT_TEMPLATE = json.loads((EXPERIMENTS.parents[1] / 'inference_config.json').read_text())['chat_template']['jinja']
RECIPE_CODE_SHA256 = hashlib.sha256((EXPERIMENTS / 'stage2_recipe.py').read_bytes()).hexdigest()
'''
        elif label == '# [recipe-functions]':
            source = '# [recipe-functions]\nfrom stage2_recipe import build_recipe, fetch_allowed_records, stable_hash\n'
        elif label == '# [workspace]':
            old = "    if not torch.cuda.is_available() or 'T4' not in torch.cuda.get_device_name(0):\n        raise RuntimeError('ランタイムをT4 GPUへ変更してください。')\n    from google.colab import drive\n    drive.mount('/content/drive')"
            assert old in source, 'Training workspace cell changed; review the remote adaptation.'
            source = source.replace(old, "    if not torch.cuda.is_available():\n        raise RuntimeError('CUDA GPUが見つかりません。')\n    print('GPU:', torch.cuda.get_device_name(0), flush=True)")
        elif label == '# [restore-stage1]':
            source = source.replace("print('merge完了。セッションのみ再起動 → PHASE=\"train\" → すべて実行。')", "print('Stage 1復元完了。次は別プロセスでStage 2を学習します。')")
        parts.append(source)
    worker = '\n\n'.join(parts) + '\n'
    compile(worker, 'run02_worker.py', 'exec')
    (HERE / 'run02_worker.py').write_text(worker)


if __name__ == '__main__':
    build()
